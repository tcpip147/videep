from __future__ import annotations

from collections.abc import AsyncIterator
from typing import Protocol, runtime_checkable

from videep.core.capabilities import DeviceCapability
from videep.core.frame import GpuFrame
from videep.core.lease import GpuResourceLease
from videep.core.sync import Synchronizer


@runtime_checkable
class ResourcePool(Protocol):
    async def acquire(self, owner: str) -> GpuResourceLease: ...
    async def close(self) -> None: ...


@runtime_checkable
class Decoder(Protocol):
    def __aiter__(self) -> AsyncIterator[GpuFrame]: ...
    async def close(self) -> None: ...


@runtime_checkable
class Encoder(Protocol):
    async def encode(self, frame: GpuFrame) -> None: ...
    async def close(self) -> None: ...


@runtime_checkable
class Backend(Protocol):
    @property
    def backend_id(self) -> str: ...
    def enumerate_devices(self) -> tuple[DeviceCapability, ...]: ...
    def create_pool(self, device_id: str, capacity: int) -> ResourcePool: ...
    def create_synchronizer(self, device_id: str) -> Synchronizer: ...
    def create_decoder(self, input_uri: str, pool: ResourcePool) -> Decoder: ...
    def create_encoder(self, output_uri: str, device_id: str) -> Encoder: ...
